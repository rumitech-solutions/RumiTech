// Zero-dependency static site generator.  Usage: node scripts/build.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import site from '../site.config.mjs';
import { products, enabledProjects, STATUS } from '../src/data/products.mjs';
import { warnings, warn } from '../src/lib/ui.mjs';
import { homePages } from '../src/pages/home.mjs';
import { productPages } from '../src/pages/products.mjs';
import { projectPages } from '../src/pages/projects.mjs';
import { companyPages } from '../src/pages/company.mjs';
import { extraPages } from '../src/pages/extras.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');

fs.rmSync(dist, { recursive: true, force: true });
fs.mkdirSync(dist, { recursive: true });
fs.cpSync(path.join(root, 'public'), dist, { recursive: true });
fs.copyFileSync(path.join(root, 'src/styles/site.css'), path.join(dist, 'assets/site.css'));

const pages = [...homePages(), ...productPages(), ...projectPages(), ...companyPages(), ...extraPages()];

for (const p of pages) {
  const file = p.file || (p.path === '/' ? 'index.html' : `${p.path.slice(1)}/index.html`);
  const out = path.join(dist, file);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, p.html);
}

// site data for the chat assistant and search palette (verified facts only)
const feat = (p) => (site.publishUnverified ? p.features : p.features.filter((x) => x.verified)).map((x) => ({ title: x.title, text: x.text }));
const data = {
  name: site.name,
  email: site.contact.email || '',
  products: products.map((p) => ({
    slug: p.slug, name: p.name, tagline: p.tagline, category: p.category, summary: p.summary, audience: p.audience,
    status: p.status, statusLabel: STATUS[p.status]?.label || '', features: feat(p),
    platforms: p.platforms.filter((x) => x.verified).map((x) => x.name),
    links: Object.fromEntries(Object.entries(p.links).filter(([, v]) => v)),
    url: `/products/${p.slug}`, privacy: `/products/${p.slug}/privacy`, location: !!p.locationProduct,
  })),
  projects: enabledProjects().map((p) => ({ slug: p.slug, name: p.name, summary: p.summary, statusLabel: STATUS[p.status]?.label || '', url: `/projects/${p.slug}` })),
  pages: [
    ['Home', '/', 'home start'], ['Products', '/products', 'apps all products'], ['Projects', '/projects', 'experiments'],
    ['About', '/about', 'company studio who'], ['FAQ', '/faq', 'questions help answers search'], ['Brand kit', '/brand', 'logo colours fonts press media'], ['Contact', '/contact', 'email support feedback'], ['Website privacy', '/privacy', 'policy data cookies'],
    ...products.flatMap((p) => [[p.name, `/products/${p.slug}`, `${p.category} ${p.tagline}`], [`${p.name} privacy`, `/products/${p.slug}/privacy`, 'policy data']]),
    ...enabledProjects().map((p) => [p.name, `/projects/${p.slug}`, 'project']),
  ].map(([title, url, kw]) => ({ title, url, kw })),
};
fs.writeFileSync(path.join(dist, 'assets/site-data.json'), JSON.stringify(data));

// sitemap + robots
const indexable = pages.filter((p) => p.path !== '/404');
const urls = indexable.map((p) => site.origin + (p.path === '/' ? '/' : p.path));
fs.writeFileSync(
  path.join(dist, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.map((u) => `  <url><loc>${u}</loc></url>`).join('\n')}\n</urlset>\n`
);
fs.writeFileSync(path.join(dist, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${site.origin}/sitemap.xml\n`);

// ── validation ──
const known = new Set(pages.map((p) => p.path));
const assetOk = (u) => fs.existsSync(path.join(dist, u.replace(/^\//, '')));
let broken = 0;
for (const p of pages) {
  const html = p.html;
  for (const m of html.matchAll(/(?:href|src)="(\/[^"#?]*)(?:[#?][^"]*)?"/g)) {
    const u = m[1];
    const clean = u.length > 1 ? u.replace(/\/$/, '') : u;
    if (known.has(clean) || assetOk(u)) continue;
    console.error(`BROKEN LINK on ${p.path}: ${u}`);
    broken++;
  }
  for (const m of html.matchAll(/href="#([^"]+)"/g)) {
    if (!html.includes(`id="${m[1]}"`)) { console.error(`BROKEN ANCHOR on ${p.path}: #${m[1]}`); broken++; }
  }
  const h1 = (html.match(/<h1[\s>]/g) || []).length;
  if (h1 !== 1) { console.error(`HEADING: ${p.path} has ${h1} <h1>`); broken++; }
}

/* palette pages updated above */
if (site.origin.includes('rumitech.example')) warn('Site origin is the placeholder https://rumitech.example — set SITE_ORIGIN or site.config.mjs.');

console.log(`Built ${pages.length} pages, sitemap with ${urls.length} URLs → dist/`);
if (warnings.length) {
  fs.writeFileSync(
    path.join(root, 'OWNER-TODO.md'),
    `# Items to confirm before publishing\n\nGenerated by \`npm run build\`. Resolve these, then set \`showDraftNotices: false\` in site.config.mjs.\n\n${warnings.map((w) => '- ' + w).join('\n')}\n`
  );
  console.log(`\n${warnings.length} owner item(s) still to confirm — see OWNER-TODO.md`);
}
if (broken) { console.error(`\n${broken} problem(s) found.`); process.exit(1); }
